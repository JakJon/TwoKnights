// Knightly Orders — the thematic upgrade classes. Neutral = classless stat upgrades
// that never receive draft affinity (they are the reliable filler pool).
public enum UpgradeOrder
{
    Neutral = 0,
    Serpent = 1,  // poison
    Shadow = 2,   // ninja / shadow arrows
    Bulwark = 3,  // tank / shield
    Ember = 4,    // fire
    Dawn = 5      // healing
}
